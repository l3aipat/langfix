// Plays each message the user means to send through the real corrector, as someone who never
// switches layout by hand, and writes the message box after every key as Swift for make-promo.swift.
// Fails if LangFix would not end on exactly the intended text, so the clip never shows more than
// the app really does. Run through scripts/promo-timeline.sh, which links the app's lexicon.
import AppKit

let lexicon = SpellLexicon()
var layout = Language.english
var output = "// Generated by scripts/promo-timeline.sh. Do not edit by hand.\nlet generatedReplies: [[KeyState]] = [\n"
var failed = false

for intended in CommandLine.arguments.dropFirst() {
    var corrector = Corrector(lexicon: lexicon)
    var field = ""
    var states: [String] = []
    for scalar in intended.unicodeScalars {
        let code = { (l: Language) in l == .thai ? "TH" : "EN" }
        func apply(_ c: Correction) {
            field = String(String.UnicodeScalarView(field.unicodeScalars.dropLast(c.deleteCount))) + c.insert
            layout = c.switchTo
        }
        if scalar == " " {
            if let c = corrector.endWord(in: layout) {
                apply(c)
                states.append("(\" \", \"\(field)\", \"\(code(layout))\", \"\(layout == .thai ? "ก" : "A")\")")
            } else {
                field += " "
                states.append("(\" \", \"\(field)\", \"\(code(layout))\", nil)")
            }
            continue
        }
        let language = Keyboard.language(of: scalar) ?? .english
        let key = Keyboard.position(of: scalar, in: language) ?? Keyboard.position(of: scalar, in: language.other)!
        let keyName = String(Keyboard.character(at: key, in: .english)).replacingOccurrences(of: "\"", with: "\\\"")
        let produced = Keyboard.character(at: key, in: layout)
        if let c = corrector.type(produced, in: layout) {
            apply(c)
            states.append("(\"\(keyName)\", \"\(field)\", \"\(code(layout))\", \"\(layout == .thai ? "ก" : "A")\")")
        } else {
            field.unicodeScalars.append(produced)
            states.append("(\"\(keyName)\", \"\(field)\", \"\(code(layout))\", nil)")
        }
    }
    if field != intended {
        FileHandle.standardError.write("LangFix would not produce \"\(intended)\", it ends on \"\(field)\"\n".data(using: .utf8)!)
        failed = true
    }
    output += "    [\n" + states.map { "        \($0)," }.joined(separator: "\n") + "\n    ],\n"
}
output += "]\n"
if failed { exit(1) }
print(output, terminator: "")
